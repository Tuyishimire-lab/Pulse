/**
 * generate-seed-sql.js
 *
 * Reads SITES from sites.ts as the single source of truth and regenerates
 * the INSERT statements for supabase_setup.sql.
 *
 * Usage: node --experimental-vm-modules scripts/generate-seed-sql.js
 *   or:  npx tsx scripts/generate-seed-sql.js
 *
 * Output goes to stdout - pipe to a file:
 *   npx tsx scripts/generate-seed-sql.js > supabase_seed_generated.sql
 */

// ESM-compatible dynamic import of the TypeScript source via tsx
const { SITES } = await import('../src/app/data/sites.ts');

function esc(v) {
  if (v === null || v === undefined) return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}

const lines = SITES.map((s) => {
  const cols = [
    'id', 'name', 'url', 'rank', 'category',
    'baseline', 'baseline_raw', 'rate', 'logo',
    'color', 'glow', 'progress'
  ].join(', ');

  const vals = [
    esc(s.id),
    esc(s.name),
    esc(s.url),
    s.rank,
    esc(s.category),
    esc(s.baseline),
    s.baselineRaw,
    s.rate,
    esc(s.logo),
    esc(s.color),
    esc(s.glow),
    s.progress,
  ].join(', ');

  return `INSERT INTO public.sites (${cols}) VALUES (${vals})\n  ON CONFLICT (id) DO UPDATE SET\n    name = EXCLUDED.name, url = EXCLUDED.url, rank = EXCLUDED.rank,\n    category = EXCLUDED.category, baseline = EXCLUDED.baseline,\n    baseline_raw = EXCLUDED.baseline_raw, rate = EXCLUDED.rate,\n    logo = EXCLUDED.logo, color = EXCLUDED.color, glow = EXCLUDED.glow,\n    progress = EXCLUDED.progress;`;
});

console.log('-- AUTO-GENERATED by scripts/generate-seed-sql.js');
console.log('-- Source of truth: src/app/data/sites.ts');
console.log(`-- ${SITES.length} sites | Generated: ${new Date().toISOString()}`);
console.log('-- Run: npx tsx scripts/generate-seed-sql.js > supabase_seed_generated.sql\n');
console.log(lines.join('\n'));
