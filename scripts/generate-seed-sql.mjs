/**
 * generate-seed-sql.mjs
 *
 * Reads SITES from sites.ts as the single source of truth and regenerates
 * the INSERT statements for supabase_setup.sql.
 *
 * Usage: npx tsx scripts/generate-seed-sql.mjs > supabase_seed_generated.sql
 */

import { SITES } from '../src/app/data/sites.ts';
import fs from 'fs';
import path from 'path';

function esc(v) {
  if (v === null || v === undefined) return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}

const lines = SITES.map((s) => {
  const cols = [
    'id', 'name', 'url', 'rank', 'category',
    'baseline', 'baseline_raw', 'rate', 'color',
    'glow', 'progress'
  ].join(', ');

  const vals = [
    esc(s.id),
    esc(s.name),
    esc(s.url),
    s.rank,
    esc(s.category),
    esc(s.baseline),
    s.baselineRaw,
    s.rate,
    esc(s.color),
    esc(s.glow),
    s.progress,
  ].join(', ');

  return `INSERT INTO public.sites (${cols}) VALUES (${vals})
  ON CONFLICT (id) DO UPDATE SET
    name = EXCLUDED.name, url = EXCLUDED.url, rank = EXCLUDED.rank,
    category = EXCLUDED.category, baseline = EXCLUDED.baseline,
    baseline_raw = EXCLUDED.baseline_raw, rate = EXCLUDED.rate,
    color = EXCLUDED.color, glow = EXCLUDED.glow,
    progress = EXCLUDED.progress;`;
});

const output = [
  '-- AUTO-GENERATED by scripts/generate-seed-sql.mjs',
  '-- Source of truth: src/app/data/sites.ts',
  `-- ${SITES.length} sites | Generated: ${new Date().toISOString()}`,
  '-- Paste this into your Supabase SQL Editor to sync all 136 domains\n',
  lines.join('\n')
].join('\n');

const outPath = path.resolve(process.cwd(), 'supabase', 'supabase_seed_generated.sql');
fs.writeFileSync(outPath, output, 'utf8');
console.log(`Successfully generated SQL seed file with ${SITES.length} domains at: ${outPath}`);
